"""Extract UI textures only; never modify calibrated resource profiles or game files."""
import argparse, base64, hashlib, json, re, subprocess, zipfile
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def build(gt_source, mods, minecraft):
    gt=Path(gt_source); assets=gt/'src/main/resources/assets'
    blocks=assets/'gregtech/textures/blocks'; fluid_dir=blocks/'fluids'
    materials=(gt/'src/main/java/gregtech/loaders/materials/MaterialsInit.java').read_text('utf-8')
    mixes=(gt/'src/main/java/gregtech/api/enums/OreMixes.java').read_text('utf-8')
    p=json.loads((ROOT/'private-packs/runtime-session/resource-profile.json').read_text('utf-8'))
    asteroids=json.loads((ROOT/'private-packs/runtime-session/asteroid-resource-profile.json').read_text('utf-8'))
    names=json.loads((ROOT/'tools/dimension-names.json').read_text('utf-8'))
    out=ROOT/'dist/assets/resources';out.mkdir(parents=True,exist_ok=True)
    work=ROOT/'artifacts/resource-icon-input';work.mkdir(parents=True,exist_ok=True)
    recipes={};catalog={};provenance={}

    def material(name):
        match=re.search(r'private static Materials load'+re.escape(name)+r'\(\) \{(.*?)\n    \}',materials,re.S)
        if not match:raise ValueError('Unknown material '+name)
        body=match[1];color=re.search(r'\.setARGB\(0x([0-9a-fA-F]+)\)',body)
        texture=re.search(r'\.setIconSet\(TextureSet.SET_(\w+)\)',body)
        return f'{int(color[1],16)&0xffffff:06x}' if color else 'ffffff',texture[1]

    def archive(pattern, entry):
        jars=list(Path(mods).glob(pattern)) if pattern else [Path(minecraft)]
        if len(jars)!=1:raise ValueError('Select one archive: '+str(jars))
        with zipfile.ZipFile(jars[0]) as z:data=z.read(entry)
        file=work/(hashlib.sha256(data).hexdigest()[:20]+'.png');file.write_bytes(data)
        return file

    def add(source, *, tint='ffffff', background=None, cube=True, origin='captured ore sprite'):
        parts=[Path(source).read_bytes(),tint.encode(),Path(background).read_bytes() if background else b'',str(cube).encode()]
        stem=hashlib.sha256(b'\0'.join(parts)).hexdigest()[:20]
        recipes[stem]='\t'.join([stem,str(source),tint,str(background or ''),'','cube' if cube else 'flat'])
        provenance[stem]=origin
        return {'flat':stem+'-flat',**({'cube':stem+'-cube'} if cube else {})}

    ore_files={}
    for key,ore in p['ores'].items():
        data=base64.b64decode(ore['icon']);file=work/(hashlib.sha256(data).hexdigest()[:20]+'.png');file.write_bytes(data)
        ore_files[key]=file

    fluid_materials={'carbondioxide':'CarbonDioxide','carbonmonoxide':'CarbonMonoxide','chlorobenzene':'Chlorobenzene',
      'ethane':'Ethane','ethylene':'Ethylene','hydrofluoricacid_gt5u':'HydrofluoricAcid','saltwater':'SaltWater'}
    external={'lava':(None,'assets/minecraft/textures/blocks/lava_still.png'),
      'ic2distilledwater':('industrialcraft-2-*.jar','assets/ic2/textures/blocks/fluids/distilledwater_still.png'),
      'unknowwater':('GalaxySpace-*.jar','assets/galaxyspace/textures/blocks/barnarda2/barnarda2unknowwaterstill.png')}
    def fluid(display):
        id=display['id'];file=fluid_dir/('fluid.'+id+'.png');tint='ffffff'
        if id in external:file=archive(*external[id])
        elif not file.exists():
            name=id.split('.',1)[1].capitalize() if id.startswith('molten.') else fluid_materials[id]
            tint,_=material(name)
            file=fluid_dir/('fluid.molten.autogenerated.png' if id.startswith('molten.') else 'fluid.autogenerated.png')
        return add(file,tint=tint,cube=False,origin='fluid texture: '+id)

    for d in p['dimensions']:
        key=names[d['name']][0];entry=catalog.setdefault(key,{'ORES':{},'FLUID':{}})
        for ore in d.get('ores',[]):
            ref=ore['display']
            if ref is not None:entry['ORES'][p['ores'][ref]['id']]=add(ore_files[ref])
        for value in d.get('fluids',[]):
            if value['display']:entry['FLUID'][value['display']['id']]=fluid(value['display'])

    ice=archive(None,'assets/minecraft/textures/blocks/ice_packed.png')
    for d in asteroids['dimensions']:
        key=names[d['name']][0];entry=catalog.setdefault(key,{'ORES':{},'FLUID':{}})
        for stone in d['materials']:
            for e in stone['veins']+stone['small']:
                display=e['display'];id=display['id'];oreid=id.split(':',1)[1]
                ref=str(d['id'])+':'+oreid
                if ref not in ore_files:ref=next((k for k,v in p['ores'].items() if v['id']==oreid),None)
                if ref:entry['ORES'][id]=add(ore_files[ref])
                else:
                    mix=re.search(r'\.name\("'+re.escape(oreid)+r'"\)(.*?)(?=\n    \w+\(new OreMixBuilder|\Z)',mixes,re.S)
                    primary=re.search(r'\.primary\(Materials\.(\w+)\)',mix[1])[1]
                    color,texture=material(primary)
                    entry['ORES'][id]=add(blocks/'materialicons'/texture/'ore.png',tint=color,background=ice,origin='packed ice ore: '+primary)

    spec=work/'render.tsv';spec.write_text('\n'.join(recipes.values()),'utf-8')
    subprocess.run(['java','-Djava.awt.headless=true',str(ROOT/'tools/RenderResourceIcons.java'),str(spec),str(out)],check=True)
    (out/'catalog.js').write_text('// Generated by tools/import-resource-icons.py; visual assets only.\nexport const resourceIconCatalog = '+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+';\n','utf-8')
    (out/'sources.json').write_text(json.dumps({'sources':provenance,'geometry':'Amidst ProspectingTextures.dimensionIcon; side lighting 0.82 / 0.62','fluidFrames':'first still-texture frame; material tint for autogenerated sprites'},indent=2)+'\n','utf-8')
    print('Resource icon coverage:',sum(len(e['ORES']) for e in catalog.values()),'ore entries,',sum(len(e['FLUID']) for e in catalog.values()),'fluid entries.')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gt-source',required=True);parser.add_argument('--mods',required=True);parser.add_argument('--minecraft',required=True)
    a=parser.parse_args();build(a.gt_source,a.mods,a.minecraft)
